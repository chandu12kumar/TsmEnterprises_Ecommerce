export const formatPrice = (price) => {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(price);
};

export const formatKm = (km) => {
  return new Intl.NumberFormat('en-IN').format(km) + ' KM';
};
